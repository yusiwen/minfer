//! NFC normalization of tokenizer input.
//!
//! Every reference `tokenizer.json` this engine gates against declares
//! `"normalizer": {"type": "NFC"}` (Qwen2.5, Qwen3 and the Qwen3.5 tokenizer the
//! `qwen35` pre-tokenizer is ported from), so the reference token ids already
//! contain the normalization: a decomposed input (`e` + U+0301) must tokenize
//! exactly like its composed form. minfer used to apply nothing, which made
//! decomposed text silently different from the model's own tokenizer; it now
//! normalizes at the two text→ids entry points ([`tokenizer`](super)).
//!
//! **Divergence, deliberate and recorded.** llama.cpp applies no normalizer for
//! byte-level BPE, so on non-NFC input the two engines disagree. minfer follows
//! the model's declared normalizer instead; the corpus the id gate uses is NFC,
//! so the gate is unaffected. See `docs/CHAT-TEMPLATE-AND-TOKENIZER-DESIGN.md`
//! §3.4 and ADR-0042.
//!
//! **Tables.** The project carries no Unicode data dependency, so the three
//! tables (canonical decomposition, canonical combining class, canonical
//! composition) are generated by `scripts/gen_unicode_nfc.py` from CPython's
//! bundled `unicodedata` and committed. Hangul syllable composition and
//! decomposition are algorithmic (UAX #15 §10) and stay out of the tables.
//! `tests/fixtures/tokenizer/nfc_vectors.json` holds CPython's own answer for
//! 2 617 inputs, which is the gate for this module's algorithm.

use std::borrow::Cow;

mod tables;

#[cfg(test)]
mod tests;

/// The Unicode data version the generated tables come from
/// (CPython's bundled `unicodedata`), asserted against the vector fixture.
pub const UNICODE_VERSION: &str = tables::UNICODE_VERSION;

// A private module in a binary crate makes an unread constant dead code; this
// keeps the version reachable from the non-test build as well.
const _: () = assert!(!UNICODE_VERSION.is_empty());

/// Hangul syllable arithmetic constants (UAX #15 §10).
const S_BASE: u32 = 0xAC00;
const L_BASE: u32 = 0x1100;
const V_BASE: u32 = 0x1161;
const T_BASE: u32 = 0x11A7;
const L_COUNT: u32 = 19;
const V_COUNT: u32 = 21;
const T_COUNT: u32 = 28;
const N_COUNT: u32 = V_COUNT * T_COUNT;
const S_COUNT: u32 = L_COUNT * N_COUNT;

/// The NFC form of `input`, borrowed when the input is already normalized.
///
/// ASCII short-circuits (no character below U+0080 decomposes, carries a
/// combining class, or composes), and so does any text whose characters can
/// neither decompose, reorder, nor start a composition. Everything else is
/// decomposed, canonically ordered and recomposed; the recomposed string is
/// compared to the input so common precomposed text (`café`) still borrows.
pub fn nfc(input: &str) -> Cow<'_, str> {
    if input.is_ascii() || !needs_normalization(input) {
        return Cow::Borrowed(input);
    }
    let composed = compose(canonical_order(decompose(input)));
    let mut out = String::with_capacity(input.len());
    for cp in composed {
        out.push(char::from_u32(cp).expect("NFC composition produced a non-character"));
    }
    if out == input {
        Cow::Borrowed(input)
    } else {
        Cow::Owned(out)
    }
}

/// Whether `input` can change under NFC at all: a character that decomposes
/// (canonically), a combining mark that may need reordering, a conjoining jamo
/// that may compose, or a character that can be the second half of a canonical
/// composition — the last matters because Indic vowel signs compose with a
/// combining class of 0, so neither of the first two tests sees them. A
/// conservative test: a `true` answer only means the full pipeline runs.
fn needs_normalization(input: &str) -> bool {
    input.chars().any(|c| {
        let cp = c as u32;
        decomposition_of(cp).is_some()
            || combining_class(cp) != 0
            || is_hangul_jamo(cp)
            || is_composition_second(cp)
    })
}

/// L, V or T jamo — the modern ranges that participate in Hangul composition.
fn is_hangul_jamo(cp: u32) -> bool {
    (L_BASE..L_BASE + L_COUNT).contains(&cp)
        || (V_BASE..V_BASE + V_COUNT).contains(&cp)
        || (T_BASE + 1..T_BASE + T_COUNT).contains(&cp)
}

fn is_composition_second(cp: u32) -> bool {
    tables::COMPOSITION_SECOND.binary_search(&cp).is_ok()
}

fn is_hangul_syllable(cp: u32) -> bool {
    (S_BASE..S_BASE + S_COUNT).contains(&cp)
}

/// Canonical decomposition of `cp`, or `None` when it has none.
fn decomposition_of(cp: u32) -> Option<&'static [u32]> {
    tables::DECOMPOSITION
        .binary_search_by_key(&cp, |&(c, _)| c)
        .ok()
        .map(|i| tables::DECOMPOSITION[i].1)
}

/// Canonical combining class of `cp`; 0 for a starter.
fn combining_class(cp: u32) -> u8 {
    tables::COMBINING_CLASS
        .binary_search_by_key(&cp, |&(c, _)| c)
        .ok()
        .map_or(0, |i| tables::COMBINING_CLASS[i].1)
}

/// A fresh decomposer so the recursion can push in order.
fn decompose(input: &str) -> Vec<u32> {
    let mut out = Vec::with_capacity(input.len());
    for c in input.chars() {
        push_decomposed(c as u32, &mut out);
    }
    out
}

fn push_decomposed(cp: u32, out: &mut Vec<u32>) {
    if is_hangul_syllable(cp) {
        // SBase + (L * VCount + V) * TCount + T
        let s = cp - S_BASE;
        out.push(L_BASE + s / N_COUNT);
        out.push(V_BASE + (s % N_COUNT) / T_COUNT);
        if s % T_COUNT != 0 {
            out.push(T_BASE + s % T_COUNT);
        }
        return;
    }
    match decomposition_of(cp) {
        // Recursive: a decomposition's parts may themselves decompose
        // (U+212B → U+00C5 → U+0041 U+030A).
        Some(parts) => {
            for &part in parts {
                push_decomposed(part, out);
            }
        }
        None => out.push(cp),
    }
}

/// Canonical ordering: within each maximal run of characters with a non-zero
/// combining class, sort by that class, stably (equal classes keep their
/// relative order).
fn canonical_order(mut cps: Vec<u32>) -> Vec<u32> {
    let mut i = 0;
    while i < cps.len() {
        if combining_class(cps[i]) == 0 {
            i += 1;
            continue;
        }
        let start = i;
        while i < cps.len() && combining_class(cps[i]) != 0 {
            i += 1;
        }
        cps[start..i].sort_by_key(|&cp| combining_class(cp));
    }
    cps
}

/// Canonical composition (UAX #15 §5.1's compose step, over an ordered,
/// decomposed sequence).
///
/// A character C is *blocked* from the last starter L when at least one
/// character pushes in between with a combining class `>= ccc(C)` — since the
/// sequence is canonically ordered, the previous character's class is the
/// maximum of the run, and a class of 0 means the previous character *is* L
/// (nothing in between). A character consumed by a composition leaves no
/// character between L and the next candidate, which is why `last_class` is
/// only updated on push.
fn compose(cps: Vec<u32>) -> Vec<u32> {
    let mut out: Vec<u32> = Vec::with_capacity(cps.len());
    let mut starter: Option<usize> = None;
    let mut last_class: u8 = 0;
    for cp in cps {
        let class = combining_class(cp);
        if let Some(si) = starter {
            let blocked = out.len() > si + 1 && last_class >= class;
            if !blocked {
                if let Some(composed) = compose_pair(out[si], cp) {
                    out[si] = composed;
                    continue;
                }
            }
        }
        if class == 0 {
            starter = Some(out.len());
        }
        last_class = class;
        out.push(cp);
    }
    out
}

/// The character `a` + `b` composes to, if any. Hangul first (algorithmic),
/// then the canonical composition table.
fn compose_pair(a: u32, b: u32) -> Option<u32> {
    if (L_BASE..L_BASE + L_COUNT).contains(&a) && (V_BASE..V_BASE + V_COUNT).contains(&b) {
        return Some(S_BASE + ((a - L_BASE) * V_COUNT + (b - V_BASE)) * T_COUNT);
    }
    if is_hangul_syllable(a)
        && (a - S_BASE) % T_COUNT == 0
        && (T_BASE + 1..T_BASE + T_COUNT).contains(&b)
    {
        return Some(a + (b - T_BASE));
    }
    tables::COMPOSITION
        .binary_search_by_key(&(a, b), |&(x, y, _)| (x, y))
        .ok()
        .map(|i| tables::COMPOSITION[i].2)
}
