#!/usr/bin/env python3
"""Generate the tokenizer's NFC tables and the differential test vectors.

The tokenizer applies NFC to its input because every reference `tokenizer.json`
this engine gates against declares `"normalizer": {"type": "NFC"}` — so the
reference token ids already contain the normalization and minfer's must too
([#132](https://github.com/yusiwen/minfer/issues/132), slice S1). The project
carries no Unicode data dependency, so the data is generated once, committed and
reviewed:

- `src/tokenizer/nfc/tables.rs` — canonical decomposition, canonical combining
  class, and canonical composition (the last derived by asking CPython whether
  the pair composes, which is exactly the exclusion rule).
- `tests/fixtures/tokenizer/nfc_vectors.json` — the differential corpus. Every
  entry is `unicodedata.normalize("NFC", input)` from the same CPython that
  produced the tables, so the Rust algorithm is checked against an independent
  implementation (the data source is shared; the algorithm is not).

Regenerate (from the repository root):

    python3 scripts/gen_unicode_nfc.py

The random section is seeded, so a re-run against the same `unicodedata`
produces identical tables and vectors (only the recorded date moves), and both
outputs name the data version they came from. A Unicode upgrade is therefore a
reviewable diff.
"""

from __future__ import annotations

import json
import platform
import random
import unicodedata
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "src" / "tokenizer" / "nfc" / "tables.rs"
VECTORS = ROOT / "tests" / "fixtures" / "tokenizer" / "nfc_vectors.json"

# Hangul syllable composition is algorithmic (UAX #15 §10), so those code points
# stay out of the generated tables — 11 172 composition pairs would only bloat
# the file, and the algorithm is pinned by the vectors below instead.
S_BASE, L_BASE, V_BASE, T_BASE = 0xAC00, 0x1100, 0x1161, 0x11A7
L_COUNT, V_COUNT, T_COUNT = 19, 21, 28
N_COUNT = V_COUNT * T_COUNT
S_COUNT = L_COUNT * N_COUNT


def is_surrogate(cp: int) -> bool:
    return 0xD800 <= cp <= 0xDFFF


def is_hangul_syllable(cp: int) -> bool:
    return S_BASE <= cp < S_BASE + S_COUNT


def canonical_decomposition(cp: int) -> list[int] | None:
    """The canonical (not compatibility) decomposition of `cp`, or None."""
    raw = unicodedata.decomposition(chr(cp))
    if not raw or raw.startswith("<"):
        return None
    return [int(part, 16) for part in raw.split()]


def combining_class(cp: int) -> int:
    return unicodedata.combining(chr(cp))


def composes(a: int, b: int) -> int | None:
    """The code point `a + b` canonically composes to, or None.

    Asking CPython is the whole exclusion rule: `Full_Composition_Exclusion`
    and the blocked cases are already encoded in its NFC answer.
    """
    out = unicodedata.normalize("NFC", chr(a) + chr(b))
    if len(out) == 1 and not is_hangul_syllable(ord(out)):
        return ord(out)
    return None


def build_tables():
    decomposition: list[tuple[int, list[int]]] = []
    classes: list[tuple[int, int]] = []
    composition: list[tuple[int, int, int]] = []

    for cp in range(0x110000):
        if is_surrogate(cp):
            continue
        dec = canonical_decomposition(cp)
        if dec:
            decomposition.append((cp, dec))
        cls = combining_class(cp)
        if cls:
            classes.append((cp, cls))

    for cp, dec in decomposition:
        if len(dec) == 2:
            composed = composes(dec[0], dec[1])
            if composed is not None and composed == cp:
                composition.append((dec[0], dec[1], cp))

    composition.sort(key=lambda t: (t[0], t[1]))
    return decomposition, classes, composition


def render_tables(decomposition, classes, composition) -> str:
    version = unicodedata.unidata_version
    out: list[str] = []
    out.append("// Generated by scripts/gen_unicode_nfc.py — do not edit by hand.")
    out.append("//")
    out.append(f"// Unicode data version: {version} (CPython's bundled database)")
    out.append("//")
    out.append("// Canonical decomposition, canonical combining class and canonical")
    out.append("// composition for NFC, sorted for binary search. Hangul syllables are")
    out.append("// algorithmic and deliberately absent.")
    out.append("")
    out.append(f'pub const UNICODE_VERSION: &str = "{version}";')
    out.append("")
    out.append(f"// {len(decomposition)} entries")
    out.append("#[rustfmt::skip]")
    out.append("pub static DECOMPOSITION: &[(u32, &[u32])] = &[")
    for cp, dec in decomposition:
        parts = ", ".join(f"0x{p:04X}" for p in dec)
        out.append(f"    (0x{cp:04X}, &[{parts}]),")
    out.append("];")
    out.append("")
    out.append(f"// {len(classes)} entries")
    out.append("#[rustfmt::skip]")
    out.append("pub static COMBINING_CLASS: &[(u32, u8)] = &[")
    for cp, cls in classes:
        out.append(f"    (0x{cp:04X}, {cls}),")
    out.append("];")
    out.append("")
    out.append(f"// {len(composition)} entries")
    out.append("#[rustfmt::skip]")
    out.append("pub static COMPOSITION: &[(u32, u32, u32)] = &[")
    for a, b, cp in composition:
        out.append(f"    (0x{a:04X}, 0x{b:04X}, 0x{cp:04X}),")
    out.append("];")
    out.append("")
    # The *second* elements, sorted: the tokenizer's quick check has to recognize
    # a character that can compose with a preceding starter even when it has no
    # decomposition and combining class 0 (the Indic vowel signs, for example).
    seconds = sorted({b for _, b, _ in composition})
    out.append(f"// {len(seconds)} entries")
    out.append("#[rustfmt::skip]")
    out.append("pub static COMPOSITION_SECOND: &[u32] = &[")
    for b in seconds:
        out.append(f"    0x{b:04X},")
    out.append("];")
    out.append("")
    return "\n".join(out)


#: A mark from each class the corpus needs to order: 230 (above), 220 (below),
#: 202 (attached below), 10/11 (Hebrew), 7 (nukta), 8 (voicing), 103/118/122
#: (Indic/below), 129/130/132 (Tibetan), 218 (below left), 228 (above right).
MARK_POOL = [
    0x0300, 0x0301, 0x0302, 0x0307, 0x0308, 0x030A, 0x0316, 0x0323, 0x0327,
    0x0328, 0x0334, 0x05B0, 0x05B1, 0x093C, 0x094D, 0x09BE, 0x0E38, 0x0EB8,
    0x0F35, 0x0F71, 0x0F72, 0x0F74, 0x0F7A, 0x1AB0, 0x20D0, 0x302A, 0x302B,
    0x3099,
]


def build_vectors(decomposition, composition):
    """The committed corpus, as `(section -> count, [(input, nfc), …])`."""
    tagged: list[tuple[str, str]] = []
    section = ["?"]

    def add(text: str) -> None:
        tagged.append((section[0], text))

    # 1. Every code point with a canonical decomposition, alone. The ones whose
    #    NFC differs (singletons and composition exclusions) pin the table; the
    #    rest assert "already NFC stays put".
    section[0] = "decomposition_sweep"
    for cp, _ in decomposition:
        add(chr(cp))

    # 2. Every canonical composition pair: the whole COMPOSITION table checked
    #    against CPython, which is the compose step's gate.
    section[0] = "composition_pairs"
    for a, b, _ in composition:
        add(chr(a) + chr(b))

    # 3. Canonical ordering: every ordered pair of marks from the pool, after a
    #    starter and alone (a mark run with no starter still sorts).
    section[0] = "mark_pairs"
    for m1 in MARK_POOL:
        for m2 in MARK_POOL:
            add("a" + chr(m1) + chr(m2))
    section[0] = "lone_mark_pairs"
    for m1 in MARK_POOL:
        for m2 in MARK_POOL:
            add(chr(m1) + chr(m2))

    # 4. Curated cases: the blocked/unblocked composition pair, the UAX #15
    #    reordering example, exclusions, singletons, jamo.
    section[0] = "curated"
    add("q\u0307\u0323")          # 230 before 220 → reorders, then no composition
    add("D\u0323\u0307")          # UAX #15's example → U+1E0C U+0307
    add("d\u0307\u0323")          # reorders to the same answer as D+0323+0307
    add("a\u0301\u0302")          # á U+0302: the second mark has no pair
    add("a\u0302\u0301")          # U+1EA5: the first composition frees the second
    add("a\u0308\u0301")          # ä U+0301
    add("a\u0301\u0308")          # á U+0308
    add("a\u05B0\u0301")          # cc 10 between starter and cc 230 → á U+05B0
    add("\u0301\u0300\u0316")     # lone marks, ordering only
    add("\u0316\u0301\u0300")
    add("e\u0328\u0301")          # → U+0119 U+0301
    add("\u1100\u1161\u11A8")     # conjoining jamo L V T
    add("\u0041\u030A")           # → U+00C5 (never the U+212B singleton)
    add("\u00C5\u0301")           # → U+01FA
    add("\u0041\u0301\u0327")     # → U+00C1 U+0327
    add("\u0110\u0323")           # no composition, no reordering
    add("\u0064\u0323\u0307")
    add("\u0064\u0307\u0323")
    for cp in (0x0340, 0x0341, 0x0343, 0x0344, 0x0374, 0x037E, 0x0387, 0x1F71, 0x1FBB, 0x2126, 0x212A, 0x212B, 0xFB01, 0x2ADC):
        add(chr(cp))

    # 5. Hangul, all four shapes plus the boundaries.
    section[0] = "hangul"
    for l in (0, 1, 9, 18):
        for v in (0, 1, 10, 20):
            for t in (0, 1, 14, 27):
                jamo = chr(L_BASE + l) + chr(V_BASE + v)
                if t:
                    jamo += chr(T_BASE + t)
                add(jamo)
    for s in (S_BASE, S_BASE + 1, S_BASE + S_COUNT // 2, S_BASE + S_COUNT - 1):
        add(chr(s))
        add(chr(s) + "\u0301")    # a mark after a syllable: order, no composition
    add("\u1100\u1161\u1161")     # L V V — the second V must not compose
    add("\uAC00\u11A8")           # a composed syllable plus a trailing T

    # 6. Precomposed text that is already NFC must come back unchanged, including
    #    compatibility forms (U+FB01, fullwidth) which NFC must NOT touch.
    section[0] = "already_nfc"
    for text in ("ASCII only", "café", "naïve façade", "Ångström", "日本語", "😀🇸🇪", "ﬁle", "ｆｕｌｌ"):
        add(text)

    # 7. A seeded random corpus over an alphabet that mixes starters, combining
    #    marks of several classes, jamo and already-composed characters.
    section[0] = "random"
    alphabet = [
        "a", "e", "i", "o", "u", "n", "D", "q", "z", "\u0301", "\u0300", "\u0302",
        "\u0308", "\u0323", "\u0327", "\u0328", "\u0307", "\u0316", "\u05B0",
        "\u09BE", "\u0F71", "\u0F72", "\u1100", "\u1161", "\u11A8", "é", "Å",
        "\uAC00", "\uD55C", "中", "😀", "\u212B", "\u1E0C", "\u0F73",
    ]
    rng = random.Random(20261014)
    for _ in range(500):
        add("".join(rng.choice(alphabet) for _ in range(rng.randint(1, 6))))

    # Deduplicate by input, keeping the first occurrence and its section.
    sections: dict[str, int] = {}
    vectors: list[tuple[str, str]] = []
    seen: set[str] = set()
    for name, text in tagged:
        if text in seen:
            continue
        seen.add(text)
        sections[name] = sections.get(name, 0) + 1
        vectors.append((text, unicodedata.normalize("NFC", text)))
    return sections, vectors


def render_vectors(sections, vectors) -> str:
    doc = {
        "provenance": {
            "reference": "CPython unicodedata.normalize('NFC', input)",
            "python": f"CPython {platform.python_version()} (unicodedata {unicodedata.unidata_version})",
            "command": "python3 scripts/gen_unicode_nfc.py",
            "date": date.today().isoformat(),
        },
        "unicode_version": unicodedata.unidata_version,
        "sections": sections,
        "entries": [{"input": text, "nfc": nfc} for text, nfc in vectors],
    }
    # Compact: this is a generated data file, and the pretty form triples it.
    return json.dumps(doc, ensure_ascii=False, separators=(",", ":")) + "\n"


def main() -> int:
    decomposition, classes, composition = build_tables()
    tables = render_tables(decomposition, classes, composition)
    TABLES.parent.mkdir(parents=True, exist_ok=True)
    TABLES.write_text(tables, encoding="utf-8")

    sections, vectors = build_vectors(decomposition, composition)
    VECTORS.write_text(render_vectors(sections, vectors), encoding="utf-8")

    changed = sum(1 for text, nfc in vectors if text != nfc)
    print(f"tables: decomposition={len(decomposition)} ccc={len(classes)} composition={len(composition)}")
    print(f"tables: {TABLES.relative_to(ROOT)} ({len(tables) / 1024:.1f} KiB)")
    print(f"vectors: {len(vectors)} entries ({changed} change under NFC)")
    for name, count in sections.items():
        print(f"  {name}: {count}")
    print(f"vectors: {VECTORS.relative_to(ROOT)} ({VECTORS.stat().st_size / 1024:.1f} KiB)")
    print(f"unicode: {unicodedata.unidata_version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
