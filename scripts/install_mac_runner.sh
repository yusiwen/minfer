#!/usr/bin/env bash
# Install the self-hosted macOS runner that issue #674 needs, and the launchd agent that keeps it alive.
#
# Why this exists. GitHub's hosted macOS runners have no Metal device — measured 2026-10-24 (PR #675):
# 13 device tests red with no `MPS:` line at all, so `MTLCreateSystemDefaultDevice()` returned nil
# before a shader was compiled. `build-macos` therefore stays a compile check, and the Metal
# correctness gate is the Mac-local `scripts/mac_gate.sh` record that #678 requires a Metal-path PR to
# paste. The only shape in which a GitHub check *is* that gate is a self-hosted runner on an Apple
# Silicon Mac.
#
# What this script does (that is #674's S1):
#   - downloads the `actions/runner` tarball for osx-arm64;
#   - writes `<dir>/runner-loop.sh`, a supervisor that mints a **fresh registration token per job**
#     with `gh` and runs ONE `--ephemeral` runner, so a long-lived runner credential never sits on a
#     machine that executes PR code;
#   - writes `~/Library/LaunchAgents/com.minfer.github-runner.plist` and loads it: `RunAtLoad`,
#     `KeepAlive`, and `/usr/bin/caffeinate -dimsu` around the loop — a Mac that sleeps stops polling
#     for work *and* cuts a running suite in half, and the second failure looks like a short pass;
#   - `--check` names every unmet prerequisite and exits non-zero; `--print` renders the two files
#     and the commands without touching anything; `--uninstall` unloads the agent.
#
# What it does NOT do — the rest of #674: S2 the `metal` job in `ci.yml`, S3 the frozen baseline plus
# `scripts/check_baselines.py --check-live --box`, S4 branch protection, S5 the contract text and
# retiring #678. Until S3 runs, the runner is not the macOS reference machine: `docs/TEST-BASELINES.md`
# rows still carry the box they were measured on, and a new box gets its own label and its own rows
# (gate contract rule 5).
#
# Security. This repository is public. A self-hosted runner executes the code of the PR it picks up,
# so a fork PR must not reach it: keep the `metal` job on same-repository branches and enable
# "Require approval for all outside collaborators" in the repository settings. #674 records the rest.
#
# Usage, on the Mac:
#   scripts/install_mac_runner.sh --check                         # prerequisites only, installs nothing
#   scripts/install_mac_runner.sh                                 # install + load the agent
#   scripts/install_mac_runner.sh --print                         # render the files, change nothing
#   scripts/install_mac_runner.sh --uninstall                     # unload and remove the agent
#
# `--repo` defaults to the clone's origin, `--dir` to `~/actions-runner-minfer`, `--name` to
# `minfer-metal` and `--labels` to `metal` (the runner's own `self-hosted`, `macOS` and `ARM64` labels
# are added by the runner, so `runs-on: [self-hosted, macOS, metal]` selects it).
set -euo pipefail

plist_label=com.minfer.github-runner
plist_dir=$HOME/Library/LaunchAgents
logdir=$HOME/Library/Logs
logfile=$logdir/minfer-github-runner.log

repo=${MINFER_RUNNER_REPO:-}
dir=${MINFER_RUNNER_DIR:-$HOME/actions-runner-minfer}
name=${MINFER_RUNNER_NAME:-minfer-metal}
labels=${MINFER_RUNNER_LABELS:-metal}
version=${MINFER_RUNNER_VERSION:-}
mode=install
force=0

usage() {
  # The header's usage block is the single copy; the backticks in the pattern are literal.
  # shellcheck disable=SC2016
  sed -n '/^# Usage, on the Mac:/,/^# `--repo` defaults to/p' "$0" | sed 's/^# \{0,1\}//' >&2
  exit 2
}

say() { printf 'install_mac_runner: %s\n' "$*" >&2; }
die() {
  printf 'install_mac_runner: %s\n' "$*" >&2
  exit 1
}

while [ $# -gt 0 ]; do
  case "$1" in
    --repo) [ $# -ge 2 ] || usage; repo=$2; shift 2 ;;
    --dir) [ $# -ge 2 ] || usage; dir=$2; shift 2 ;;
    --name) [ $# -ge 2 ] || usage; name=$2; shift 2 ;;
    --labels) [ $# -ge 2 ] || usage; labels=$2; shift 2 ;;
    --version) [ $# -ge 2 ] || usage; version=$2; shift 2 ;;
    --check) mode=check; shift ;;
    --print) mode=print; shift ;;
    --uninstall) mode=uninstall; shift ;;
    --force) force=1; shift ;;
    -h | --help) usage ;;
    *) say "unknown argument: $1"; usage ;;
  esac
done

[ -n "$repo" ] || repo=$(gh repo view --json nameWithOwner -q .nameWithOwner 2>/dev/null || true)
[ -n "$repo" ] || die "no --repo and no origin to derive it from; pass --repo <owner>/<name>"

case "$dir" in
  *'&'* | *'<'* | *'>'*) die "--dir may not contain &, < or >: it is embedded in an XML plist" ;;
esac

# --- the two generated artifacts ---------------------------------------------------------------
# Both are rendered functions so that `--print` shows exactly what `--install` would write. Keep
# every runtime variable in the loop's own `$` and every installer value expanded at write time.

loop_script() {
  printf '#!/usr/bin/env bash\n'
  printf '# Generated by scripts/install_mac_runner.sh at %s — re-run the installer, do not edit.\n' \
    "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
  printf 'repo=%q\nname=%q\nlabels=%q\ndir=%q\n' "$repo" "$name" "$labels" "$dir"
  cat <<'LOOP'
set -uo pipefail
cd "$dir" || { printf 'runner-loop: cannot enter %s\n' "$dir" >&2; exit 1; }
log() { printf '%s %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$*"; }

while :; do
  token=$(gh api -X POST "repos/$repo/actions/runners/registration-token" --jq .token 2>/dev/null) || token=""
  if [ -z "$token" ]; then
    log "cannot mint a registration token for $repo (no repo admin, no gh auth, or github.com unreachable); retrying in 60s"
    sleep 60
    continue
  fi
  log "registering an ephemeral runner: name=$name labels=$labels"
  if ! ./config.sh --unattended --ephemeral --replace \
      --name "$name" --labels "$labels" --work "$dir/_work" --token "$token"; then
    log "config.sh failed; retrying in 60s"
    sleep 60
    continue
  fi
  ./run.sh
  rc=$?
  # An ephemeral runner deregisters itself after one job, so the next iteration must register again.
  log "run.sh exited $rc; re-registering"
  rm -f .runner .credentials .credentials_rsaparams 2>/dev/null
  [ "$rc" -eq 0 ] || sleep 10
done
LOOP
}

plist_content() {
  cat <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>$plist_label</string>
  <key>ProgramArguments</key>
  <array>
    <string>/usr/bin/caffeinate</string>
    <string>-dimsu</string>
    <string>/bin/bash</string>
    <string>$dir/runner-loop.sh</string>
  </array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ThrottleInterval</key><integer>60</integer>
  <key>ProcessType</key><string>Background</string>
  <key>StandardOutPath</key><string>$logfile</string>
  <key>StandardErrorPath</key><string>$logfile</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
  </dict>
</dict>
</plist>
PLIST
}

# The model paths `scripts/mac_gate.sh` hardcodes for the identity battery. Kept in one place here so
# this script's `--check` cannot promise a gate the other script cannot run.
model_target=/Volumes/WD_BLACK/models/hf/Qwen/Qwen2.5-7B-Instruct-GGUF/qwen2.5-7b-instruct-q4_k_m-00001-of-00002.gguf
model_draft=/Volumes/WD_BLACK/models/hf/Qwen/Qwen2.5-0.5B-Instruct-GGUF/qwen2.5-0.5b-instruct-q4_k_m.gguf

check_prereqs() {
  local bad=0
  report() { printf '  %-30s %s\n' "$1" "$2" >&2; }

  if [ "$(uname -s)" = Darwin ]; then
    report "macOS" "ok ($(sw_vers -productVersion))"
  else
    report "macOS" "NO ($(uname -s)) — the Metal suite needs an Apple Silicon Mac"
    bad=$((bad + 1))
  fi

  case "$(uname -m)" in
    arm64 | aarch64) report "architecture" "ok ($(uname -m))" ;;
    *)
      report "architecture" "NO ($(uname -m)) — the tarball is osx-arm64 and the Metal baseline is Apple Silicon"
      bad=$((bad + 1))
      ;;
  esac

  if command -v gh >/dev/null 2>&1; then
    if gh auth status >/dev/null 2>&1; then
      report "gh" "ok ($(gh --version | head -1))"
    else
      report "gh" "NO — \`gh auth login\` first; the loop mints a token per job"
      bad=$((bad + 1))
    fi
  else
    report "gh" "NO — not on PATH (Homebrew's is /opt/homebrew/bin/gh)"
    bad=$((bad + 1))
  fi

  # Reaching github.com is a prerequisite in its own right: the loop polls it, and the tarball comes
  # from the same host. One API call proves both the token's scope and the network path.
  if gh api "repos/$repo" --jq .full_name >/dev/null 2>&1; then
    if [ "$(gh api "repos/$repo" --jq .permissions.admin 2>/dev/null)" = true ]; then
      report "repo admin ($repo)" "ok"
    else
      report "repo admin ($repo)" "NO — minting a registration token needs admin"
      bad=$((bad + 1))
    fi
    if gh api repos/actions/runner/releases/latest --jq .tag_name >/dev/null 2>&1; then
      report "github.com egress" "ok (actions/runner release resolvable)"
    else
      report "github.com egress" "NO — cannot reach api.github.com"
      bad=$((bad + 1))
    fi
  else
    report "github.com egress" "NO — \`gh api repos/$repo\` failed (network, auth or repo name)"
    bad=$((bad + 1))
  fi

  if command -v xcrun >/dev/null 2>&1 && xcrun -sdk macosx metal --version >/dev/null 2>&1; then
    report "Metal toolchain" "ok"
  else
    report "Metal toolchain" "NO — since #788 a missing toolchain is a hard error, not a warning"
    bad=$((bad + 1))
  fi

  local miss=""
  command -v cargo >/dev/null 2>&1 || miss="$miss cargo"
  command -v git >/dev/null 2>&1 || miss="$miss git"
  if [ -z "$miss" ]; then
    report "cargo + git" "ok"
  else
    report "cargo + git" "NO — missing:$miss"
    bad=$((bad + 1))
  fi

  if [ -f "$model_target" ] && [ -f "$model_draft" ]; then
    report "identity-battery models" "ok (7B + 0.5B on the WD_BLACK volume)"
  else
    report "identity-battery models" "warn — missing under /Volumes/WD_BLACK; mac_gate.sh reports the battery as 'not run'"
  fi

  # Advisories, measured on the maintainer's box: the 7B + 0.5B battery peaks around 7 GiB, and
  # Xcode/Metal toolchain + target/ + the gate's models need roughly 60 GiB. Both are soldered.
  if command -v sysctl >/dev/null 2>&1; then
    local mem_gib
    mem_gib=$(($(sysctl -n hw.memsize) / 1073741824))
    if [ "$mem_gib" -ge 16 ]; then
      report "RAM" "ok (${mem_gib} GiB)"
    else
      report "RAM" "warn — ${mem_gib} GiB; 16 GiB is the documented floor"
    fi
  fi
  if [ "$(uname -s)" = Darwin ] && command -v df >/dev/null 2>&1; then
    local free_gib
    free_gib=$(df -g "$HOME" 2>/dev/null | awk 'NR==2 {print $4}')
    if [ -n "${free_gib:-}" ] && [ "$free_gib" -ge 60 ]; then
      report "free disk" "ok (${free_gib} GiB)"
    else
      report "free disk" "warn — ${free_gib:-?} GiB; about 60 GiB is the floor"
    fi
  fi

  return "$bad"
}

install_agent() {
  [ "$(uname -s)" = Darwin ] || die "not macOS ($(uname -s)); nothing was installed"
  check_prereqs || die "prerequisites unmet (above); nothing was installed"

  mkdir -p "$dir" "$plist_dir" "$logdir"

  if [ -z "$version" ]; then
    version=$(gh api repos/actions/runner/releases/latest --jq .tag_name) ||
      die "cannot resolve the latest actions/runner release"
  fi
  local tag=$version
  case "$tag" in v*) ;; *) tag=v$tag ;; esac
  local archive="actions-runner-osx-arm64-${tag#v}.tar.gz"

  if [ ! -x "$dir/config.sh" ] || [ "$force" = 1 ]; then
    say "downloading $archive"
    curl -fsSL "https://github.com/actions/runner/releases/download/$tag/$archive" \
      -o "$dir/$archive" || die "download failed: $tag/$archive"
    tar -xzf "$dir/$archive" -C "$dir" || die "extracting $archive failed"
    rm -f "$dir/$archive"
  else
    say "keeping the existing runner in $dir (--force re-downloads)"
  fi
  [ -x "$dir/config.sh" ] || die "$dir/config.sh missing after extraction"

  loop_script >"$dir/runner-loop.sh"
  chmod +x "$dir/runner-loop.sh"

  plist_content >"$plist_dir/$plist_label.plist"
  plutil -lint "$plist_dir/$plist_label.plist" >/dev/null ||
    die "the generated plist does not lint; nothing was loaded"

  launchctl bootout "gui/$(id -u)/$plist_label" >/dev/null 2>&1 || true
  launchctl bootstrap "gui/$(id -u)" "$plist_dir/$plist_label.plist" ||
    die "launchctl bootstrap failed; read $logfile"
  launchctl kickstart -k "gui/$(id -u)/$plist_label" >/dev/null 2>&1 || true

  say "loaded $plist_label (runner dir: $dir, log: $logfile)"
  say "it holds the Mac awake while loaded; unload with --uninstall to let it sleep"
  say "verify:"
  say "  gh api repos/$repo/actions/runners --jq '.runners[] | \"\\(.name)\\t\\(.status)\"'"
  say "  tail -f $logfile"
  say "until #674 S2 lands there is no job to pick up: the loop registers and waits"
}

uninstall_agent() {
  [ "$(uname -s)" = Darwin ] || die "not macOS ($(uname -s)); nothing to unload"
  launchctl bootout "gui/$(id -u)/$plist_label" >/dev/null 2>&1 ||
    say "no loaded agent named $plist_label"
  rm -f "$plist_dir/$plist_label.plist"
  say "unloaded and removed $plist_dir/$plist_label.plist"
  say "the runner directory $dir is kept; remove it by hand if this machine is being retired"
  say "a registration from an interrupted job may still be listed — delete it with:"
  say "  gh api repos/$repo/actions/runners --jq '.runners[] | \"\\(.id) \\(.name) \\(.status)\"'"
  say "  gh api -X DELETE repos/$repo/actions/runners/<id>"
}

print_plan() {
  printf '=== %s/runner-loop.sh\n' "$dir"
  loop_script
  printf '\n=== %s/%s.plist\n' "$plist_dir" "$plist_label"
  plist_content
  printf '\n=== install commands\n'
  printf 'mkdir -p %s %s %s\n' "$dir" "$plist_dir" "$logdir"
  printf 'curl -fsSL https://github.com/actions/runner/releases/download/<tag>/actions-runner-osx-arm64-<version>.tar.gz -o %s/<archive>\n' "$dir"
  printf 'tar -xzf %s/<archive> -C %s\n' "$dir" "$dir"
  printf 'launchctl bootout gui/%s/%s || true\n' "$(id -u)" "$plist_label"
  printf 'launchctl bootstrap gui/%s %s/%s.plist\n' "$(id -u)" "$plist_dir" "$plist_label"
  printf 'launchctl kickstart -k gui/%s/%s\n' "$(id -u)" "$plist_label"
}

case "$mode" in
  check) check_prereqs || exit 1 ;;
  print) print_plan ;;
  uninstall) uninstall_agent ;;
  install) install_agent ;;
esac
